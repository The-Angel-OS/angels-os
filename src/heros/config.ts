import type { Field } from 'payload'

import {
  FixedToolbarFeature,
  HeadingFeature,
  InlineToolbarFeature,
  lexicalEditor,
} from '@payloadcms/richtext-lexical'

import { linkGroup } from '@/fields/linkGroup'

export const hero: Field = {
  name: 'hero',
  type: 'group',
  fields: [
    {
      name: 'type',
      type: 'select',
      defaultValue: 'lowImpact',
      label: 'Type',
      options: [
        {
          label: 'None',
          value: 'none',
        },
        {
          label: 'High Impact',
          value: 'highImpact',
        },
        {
          label: 'Medium Impact',
          value: 'mediumImpact',
        },
        {
          label: 'Low Impact',
          value: 'lowImpact',
        },
        {
          // The renderer (RenderHero) and the DB enum have had `fullScreen`
          // since 260720, but it was never added here — so a hero type that
          // fully works could not be CHOSEN. It takes a video as happily as an
          // image: FullScreen autoplays a video/* upload muted and looped.
          label: 'Full Screen (image or video)',
          value: 'fullScreen',
        },
        {
          // The corporate product-page pattern: dark content slab beside the
          // photograph, accent rule under the headline.
          label: 'Split Panel (content beside image)',
          value: 'splitPanel',
        },
      ],
      required: true,
    },
    {
      name: 'richText',
      type: 'richText',
      editor: lexicalEditor({
        features: ({ rootFeatures }) => {
          return [
            ...rootFeatures,
            HeadingFeature({ enabledHeadingSizes: ['h1', 'h2', 'h3', 'h4'] }),
            FixedToolbarFeature(),
            InlineToolbarFeature(),
          ]
        },
      }),
      label: false,
    },
    linkGroup({
      overrides: {
        maxRows: 2,
      },
    }),
    {
      name: 'media',
      type: 'upload',
      admin: {
        condition: (_, { type } = {}) =>
          ['highImpact', 'mediumImpact', 'fullScreen', 'splitPanel'].includes(type),
      },
      relationTo: 'media',
      required: true,
    },
  ],
  label: false,
}
